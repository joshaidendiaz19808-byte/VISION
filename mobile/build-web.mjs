// Copies ../web into www/ for the phone apps and points it at the hosted VISION server.
// Usage: VISION_API=https://your-server npm run sync
import { cpSync, rmSync, writeFileSync } from "node:fs";

const api = (process.env.VISION_API || "").replace(/\/$/, "");
if (!/^https:\/\//.test(api)) {
  console.error("Set VISION_API to the hosted server's https:// URL, e.g.\n  VISION_API=https://vision.example.com npm run sync");
  process.exit(1);
}
rmSync("www", { recursive: true, force: true });
cpSync("../web", "www", { recursive: true });
rmSync("www/sw.js"); // the app bundle is already offline; a service worker would only serve stale files
writeFileSync("www/config.js", `// generated by build-web.mjs\nwindow.VISION_API = ${JSON.stringify(api)};\n`);
console.log(`www/ built -> API ${api}`);
